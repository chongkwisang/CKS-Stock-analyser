import 'services/app_state.dart';

/// Translate an English UI string to the current app language.
/// English is the key; missing translations fall back to English.
String t(String en) => AppState.instance.isChinese ? (_zh[en] ?? en) : en;

/// Translate a template with {placeholders}.
String tf(String en, Map<String, Object?> args) {
  var s = t(en);
  args.forEach((k, v) => s = s.replaceAll('{$k}', '${v ?? ''}'));
  return s;
}

